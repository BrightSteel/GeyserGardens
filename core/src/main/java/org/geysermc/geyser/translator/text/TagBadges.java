package org.geysermc.geyser.translator.text;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;

/**
 * Gardens fork: rewrites the Java "tag" badge glyphs (rank/rarity/cosmetic) into their Bedrock
 * equivalents.
 *
 * <p>Java renders each badge as a single wide bitmap-font glyph at a private-use codepoint
 * (e.g. U+ABE1 = player). Bedrock renders every custom glyph into a square box, so each badge is
 * pre-baked as one square emoji at a U+E3xx codepoint in the gardens-bedrock pack
 * ({@code font/glyph_E3.png}). This swaps each Java codepoint for its Bedrock emoji char, per
 * Bedrock session — Java players are never affected, so a Bedrock player's rank no longer leaks
 * broken E3xx glyphs into Java chat (the reason the server-side prefix placeholder was removed).
 *
 * <p>Applied ONLY to the text a Bedrock client displays inline — chat ({@code handleChatPacket},
 * {JavaSystem... system chat}) and item name/lore
 * ({@code BedrockItemBuilder#build()}). Deliberately NOT wired into {@code convertMessage}
 * globally: some tag codepoints are reused elsewhere — notably U+E120 is the HUD's blank gate
 * glyph in a boss-bar title — and must stay untouched in those non-chat contexts. The mapping is
 * generated by {@code gardens-bedrock/tools/j2b/tag_emoji.py} into
 * {@code bedrock_tag_badges.properties}.
 */
public final class TagBadges {

    private static final Map<Integer, String> BADGES = load();

    private TagBadges() {
    }

    private static Map<Integer, String> load() {
        Map<Integer, String> map = new HashMap<>();
        try (InputStream in = TagBadges.class.getResourceAsStream("/bedrock_tag_badges.properties")) {
            if (in == null) {
                return map;
            }
            Properties props = new Properties();
            props.load(in); // Properties.load resolves the \\uXXXX escapes in the values
            for (String key : props.stringPropertyNames()) {
                map.put(Integer.parseInt(key, 16), props.getProperty(key));
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
        return map;
    }

    /**
     * Replace every Java tag codepoint in {@code input} with its Bedrock emoji char. Returns
     * {@code input} unchanged when it holds no tag glyphs (the common case).
     */
    public static String apply(String input) {
        if (input == null || input.isEmpty() || BADGES.isEmpty()) {
            return input;
        }
        boolean has = false;
        for (int i = 0; i < input.length(); i++) {
            if (BADGES.containsKey((int) input.charAt(i))) { // tag codepoints are all in the BMP
                has = true;
                break;
            }
        }
        if (!has) {
            return input;
        }
        StringBuilder sb = new StringBuilder(input.length());
        input.codePoints().forEach(cp -> {
            String rep = BADGES.get(cp);
            sb.append(rep != null ? rep : new String(Character.toChars(cp)));
        });
        return sb.toString();
    }

    /**
     * {@link #apply(String)} over every line of {@code lines}, returning a new list.
     */
    public static List<String> applyAll(List<String> lines) {
        List<String> mapped = new ArrayList<>(lines.size());
        for (String line : lines) {
            mapped.add(apply(line));
        }
        return mapped;
    }
}
